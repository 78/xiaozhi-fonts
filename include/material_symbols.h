extern const material_symbol_t material_symbols_symbols[];
extern const size_t material_symbols_symbol_count;

static inline const char* material_symbols_get_utf8(const char* name) {
    if (name == NULL) return NULL;
    for (size_t i = 0; i < material_symbols_symbol_count; ++i) {
        if (strcmp(material_symbols_symbols[i].name, name) == 0) return material_symbols_symbols[i].utf8_string;
    }
    return NULL;
}

